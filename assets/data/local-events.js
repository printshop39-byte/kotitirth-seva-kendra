/* ============================================================
   स्थानिक कार्यक्रम — केंद्राचे स्वतःचे विशेष दिवस
   ------------------------------------------------------------
   संयोजक इथे केंद्राचे कार्यक्रम स्वतः जोडू शकतात — मुख्य पंचांग
   गणनेला हात न लावता.  प्रत्येक नोंद खालील रचनेत:

     {
       date:      "2026-08-15",   // YYYY-MM-DD (भारतीय तारीख)
       titleMr:   "कार्यक्रमाचे नाव",
       descMr:    "थोडक्यात माहिती (मोडलमध्ये दिसते).",
       type:      "event",         // "major" | "event" | "observance"
       priority:  5,                // मोठा आकडा = आधी दाखवला जातो
       showPopup: false,            // true असल्यास मोडल (एका दिवसातून एकदा)
       ctaText:   "आजची सेवा पहा",  // मोडलमधले बटण (नको असल्यास वगळा)
       ctaTarget: "seva"            // "seva" = नित्य सेवा वेळापत्रकाकडे
     }

   टीप: showPopup:true असलेला दिवस त्या तारखेस एकदाच दिसतो; भाविकाने
   "बंद करा" दाबल्यावर त्या दिवशी पुन्हा दिसत नाही (localStorage).
   ============================================================ */
(function () {
  "use strict";
  window.KT = window.KT || {};

  // डीफॉल्ट रिकामे — अधिकृत माहिती असेल तरच संयोजकांनी नोंद जोडावी.
  // (वरील टिप्पणीत नमुना-रचना दिली आहे. कोणतीही खरी तारीख/सेवा पडताळल्याशिवाय
  //  इथे टाकू नये — चुकीची live माहिती टाळण्यासाठी.)
  window.KT.LocalEvents = [];

  // दिलेल्या IST तारखेसाठी (Y,M,D) लागू स्थानिक कार्यक्रम
  window.KT.LocalEvents.forDate = function (y, mo1, d) {
    var iso = y + "-" + String(mo1).padStart(2, "0") + "-" + String(d).padStart(2, "0");
    return (window.KT.LocalEvents || []).filter(function (e) { return e && e.date === iso; });
  };
})();
